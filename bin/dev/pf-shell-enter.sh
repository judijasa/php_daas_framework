#!/usr/bin/env bash
# Dev-shell runtime bootstrap, sourced by the shellHook of this repo's
# flake (./bin/dev/pf-shell-enter.sh <PROJECT_NAME>) and of consumer flakes (shipped on PATH
# via the framework's nix package). Must be sourced (not executed): the
# .env exports and the PATH entries must reach the interactive shell. Must
# run from the repo root ($PWD).
#
# Puts the repo's CLIs on PATH: vendor/bin (Composer-delivered — the
# dependencies' bins such as `ema` and `composer`, plus the framework's own
# bins as a consumer sees them) then bin (this repo's own CLIs, which the
# root package's `bin` list does NOT link into vendor/bin). bin/ precedes
# vendor/bin so a consumer's `deploy` shadows the framework's.
#
# Loads the repo-root .env (git-ignored, generated by `make dev-init`) and
# sets the tmux session alias. Private config in etc/ is consumer-owned: the
# framework neither fetches nor injects it, so nothing is refreshed here (see
# doc/system/consumer-config.md). It does NOT start or resume a MariaDB
# daemon: the dev database instance lifecycle is owned by ema
# (`ema sandbox srv/<name>-<GUID>` builds + starts a per-instance sandbox;
# `ema status` lists the instances and the lifecycle verbs
# `ema start|stop|restart|gc` take the `var/sandbox/<name>-<GUID>` path it
# prints).

if ! (return 0 2>/dev/null); then
    echo "pf-shell-enter.sh must be sourced, not executed" >&2
    exit 1
fi

# CLIs on PATH (see the header). Each line prepends, so vendor/bin goes first
# and bin/ — prepended last — ends up ahead of it. Conditional because on a
# first `nix develop` entry vendor/bin may not exist yet (`make dev-init` runs
# composer install to populate it). Set before the argument check below: that
# check returns early, so PATH must not depend on the caller passing a name.
[ -d vendor/bin ] && export PATH="$PWD/vendor/bin:$PATH"
[ -d bin ] && export PATH="$PWD/bin:$PATH"

if [ -z "${1:-}" ]; then
    echo "usage: source pf-shell-enter.sh <PROJECT_NAME>" >&2
    return 1 2>/dev/null || exit 1
fi
PROJECT_NAME="$1"

if [ -f .env ]; then
    set -a
    . ./.env
    set +a
else
    echo "No .env found - run 'make dev-init' inside this shell (required for runtime config)."
fi

# Inherit nix shell env in tmux (doesn't include PS1)
# Requires 'set -g default-command ...' in .tmux.conf
alias tmux="command tmux -L \$PROJECT_NAME new-session -A -s \$PROJECT_NAME"
