#!/usr/bin/env bash
# Install the pre-commit framework (pre-commit + pre-push hook types) and
# wrap the pre-push shim with hooks/run-on-clean-tree.sh, so full-repo
# analyzers always run against a clean HEAD.
# Backend for the Makefile target _dev-init-git-hooks (make dev-init).

set -euo pipefail

echo "Analyzing if Pre-commit Framework is already installed (pre-commit + pre-push)..."
if [ -f ".git/hooks/pre-commit" ] && [ -f ".git/hooks/pre-push" ] && head -n 2 .git/hooks/pre-commit | grep -q "generated by pre-commit" && head -n 2 .git/hooks/pre-push | grep -q "generated by pre-commit"; then
    echo "Pre-commit Framework already installed. Skipping."
else
    echo "Installing Pre-commit Framework (pre-commit + pre-push hook types)..."
    pre-commit install
fi

echo "Wrapping pre-push shim with run-on-clean-tree (stash-on-clean-tree)..."
if [ -f ".git/hooks/pre-push" ] && grep -q "run-on-clean-tree" ".git/hooks/pre-push"; then
    echo "Pre-push shim already wrapped. Skipping."
else
    echo "Applying stash wrapper to .git/hooks/pre-push..."
    _wrap="$(git rev-parse --show-toplevel)/hooks/run-on-clean-tree.sh"
    # Insert a marker comment just before the last line (the pre-push exec).
    sed -i '$i # [php_daas_framework] modified: wrapped with run-on-clean-tree.sh (stash before pre-push gates)' .git/hooks/pre-push
    # Rewrite the trailing "exec <cmd>" line to route it through the wrapper.
    sed -i "$ s|^exec \(.*\)\$|exec "$_wrap" \1|" .git/hooks/pre-push
    chmod +x .git/hooks/pre-push
fi
